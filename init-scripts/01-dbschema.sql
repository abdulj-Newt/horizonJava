CREATE SEQUENCE "ACCOUNT_SEQ" START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE "TRANSACTION_SEQ" START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE "CUSTOMER_SEQ" START WITH 1 INCREMENT BY 1;

CREATE TABLE "CUSTOMERS" (
    "ID" NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CUSTOMER_NAME" VARCHAR2(255) NOT NULL
);

CREATE TABLE "ACCOUNTS" (
    "ID" NUMBER NOT NULL PRIMARY KEY,
    "ACCOUNT_NUMBER" VARCHAR2(255) NOT NULL UNIQUE,
    "BALANCE" NUMBER(19, 2) NOT NULL,
    "CUSTOMER_ID" NUMBER,
    CONSTRAINT "FK_CUSTOMER" FOREIGN KEY ("CUSTOMER_ID") REFERENCES "CUSTOMERS"("ID")
);

CREATE TABLE "TRANSACTIONS" (
    "ID" NUMBER NOT NULL PRIMARY KEY,
    "ACCOUNT_ID" NUMBER NOT NULL,
    "AMOUNT" NUMBER(19, 2) NOT NULL,
    "FROM_CUSTOMER" NUMBER NOT NULL,
    "TO_CUSTOMER" NUMBER NOT NULL,
    "TIMESTAMP" TIMESTAMP NOT NULL,
    "TYPE" VARCHAR2(255),
    CONSTRAINT "FK_ACCOUNT" FOREIGN KEY ("ACCOUNT_ID") REFERENCES "ACCOUNTS"("ID"),
    CONSTRAINT "FK_FROM_CUSTOMER" FOREIGN KEY ("FROM_CUSTOMER") REFERENCES "CUSTOMERS"("ID"),
    CONSTRAINT "FK_TO_CUSTOMER" FOREIGN KEY ("TO_CUSTOMER") REFERENCES "CUSTOMERS"("ID")
);